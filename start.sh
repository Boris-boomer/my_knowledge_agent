#!/bin/bash
# ============================================================
# 个人知识库问答 Agent - 启动脚本 (Linux/macOS)
# ============================================================

set -e

echo "============================================================"
echo "      个人知识库问答 Agent - 启动脚本 (Linux/macOS)"
echo "============================================================"
echo ""

# ============================================================
# 1. 检查 Python
# ============================================================
echo "[1/5] 检查 Python 环境..."
if ! command -v python3 &> /dev/null; then
    echo "❌ 未找到 Python，请安装 Python 3.12 或更高版本"
    exit 1
fi
PYTHON_VERSION=$(python3 --version | cut -d' ' -f2 | cut -d'.' -f1,2)
echo "✅ Python $PYTHON_VERSION 已就绪"
echo ""

# ============================================================
# 2. 检查 uv
# ============================================================
echo "[2/5] 检查 uv 包管理器..."
if ! command -v uv &> /dev/null; then
    echo "⚠️ uv 未安装，正在安装..."
    pip3 install uv
    if [ $? -ne 0 ]; then
        echo "❌ uv 安装失败，请手动安装: pip install uv"
        exit 1
    fi
fi
echo "✅ uv 已就绪"
echo ""

# ============================================================
# 3. 检查并安装依赖
# ============================================================
echo "[3/5] 检查依赖..."
if [ ! -d ".venv" ]; then
    echo "创建虚拟环境..."
    uv venv
fi
echo "安装依赖..."
uv pip install -r requirements.txt
if [ $? -ne 0 ]; then
    echo "❌ 依赖安装失败"
    exit 1
fi
echo "✅ 依赖已就绪"
echo ""

# ============================================================
# 4. 检查 config.yaml
# ============================================================
echo "[4/5] 检查配置文件..."
if [ ! -f "config.yaml" ]; then
    echo "⚠️ 未找到 config.yaml，使用默认配置"
    cp config.yaml.example config.yaml 2>/dev/null || true
fi
echo "✅ 配置文件已就绪"
echo ""

# ============================================================
# 5. 启动服务
# ============================================================
echo "[5/5] 启动服务..."
echo ""
echo "============================================================"
echo "   🚀 服务启动中..."
echo "   访问地址: http://localhost:7860"
echo "   按 Ctrl+C 停止服务"
echo "============================================================"
echo ""

uv run python src/app.py